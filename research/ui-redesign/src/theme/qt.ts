// What a design here becomes in the Qt app:
//   themeJson: a theme file for hosts/maya/themes/ (read by hosts/app/src/theme.cpp and the Maya host),
//   qss:       a reference Qt stylesheet for the widgets the mock uses, from the same tokens.
// The app builds its QSS from a template (theme.cpp styleSheet()); this output is the target
// that template should produce, not a file to paste over it.
import { defaults, dimensions, type Options } from "@/lab/options";
import { density, tokensFor } from "./tokens";

export function themeJson(o: Options) {
  const t = tokensFor(o);
  const d = density[o.density as keyof typeof density] ?? density.default;
  const theme = dimensions.find((x) => x.id === "theme")!.choices.find((c) => c.id === o.theme)!;
  const changed = dimensions.filter((x) => o[x.id] !== defaults[x.id]).map((x) => `${x.id}=${o[x.id]}`);
  return {
    name: `${theme.label} ${o.accent === "mono" ? "" : o.accent[0].toUpperCase() + o.accent.slice(1)}`.trim(),
    description: `From research/ui-redesign (${changed.join(", ") || "defaults"})`,
    extends: "charcoal",
    ui: {
      background: t.background,
      panel: t.panel,
      raised: t.raised,
      hover: t.hover,
      border: t.border,
      text: t.text,
      textDim: t.textDim,
      accent: t.accent,
      accentText: t.accentText,
      radius: Number(o.radius),
      fontSize: d.font,
      glass: false,
      outline: t.border,
      selection: t.selection,
      selectionText: t.text,
    },
    graph: {
      canvas: t.background,
      grid: t.border,
      node: t.panel,
      nodeBorder: t.border,
      text: t.text,
      textDim: t.textDim,
      selected: t.text,
      cornerRadius: Number(o.radius) + 2,
      shadow: false,
      // headerStyle "tinted" / "filled" are read today; the rest are new keys for the node painters.
      headerStyle: o.nodeHeader,
      nodeBody: o.nodeBody,
      wireStyle: o.wires,
      wireColors: o.wireColor,
      portShape: o.ports,
      canvasStyle: o.canvas,
      nodeStatus: o.nodeStatus,
    },
  };
}

export function qss(o: Options): string {
  const t = tokensFor(o);
  const d = density[o.density as keyof typeof density] ?? density.default;
  const r = Number(o.radius);
  const rs = Math.max(0, r - 2);
  const row = d.row;
  const inner = row - 2; // QSS min-height excludes the 1px borders
  const tabs: Record<string, string> = {
    segmented: `QTabBar { background: ${t.background}; border: 1px solid ${t.border}; border-radius: ${r}px; }
QTabBar::tab { background: transparent; color: ${t.textDim}; border: none; border-radius: ${rs}px; padding: 3px 10px; margin: 2px; }
QTabBar::tab:selected { background: ${t.raised}; color: ${t.text}; }
QTabBar::tab:hover:!selected { color: ${t.text}; }`,
    underline: `QTabBar { qproperty-drawBase: 0; border-bottom: 1px solid ${t.border}; }
QTabBar::tab { background: transparent; color: ${t.textDim}; border: none; border-bottom: 2px solid transparent; padding: 5px 0; margin-right: 12px; }
QTabBar::tab:selected { color: ${t.text}; border-bottom-color: ${t.accent}; }
QTabBar::tab:hover:!selected { color: ${t.text}; }`,
    pills: `QTabBar { qproperty-drawBase: 0; }
QTabBar::tab { background: transparent; color: ${t.textDim}; border: none; border-radius: ${Math.round(row / 2)}px; padding: 3px 12px; margin-right: 4px; }
QTabBar::tab:selected { background: ${t.accent}; color: ${t.accentText}; }
QTabBar::tab:hover:!selected { background: ${t.hover}; color: ${t.text}; }`,
  };
  const sections: Record<string, string> = {
    caps: `QToolButton[role="section"] { color: ${t.textMuted}; font-size: ${d.small}px; font-weight: 600; /* no text-transform in QSS: uppercase the label in code, letter-spacing via QFont */ border: none; border-top: 1px solid ${t.border}; padding: 4px 0; text-align: left; }`,
    cards: `QFrame[role="card"] { background: ${t.raised}; border: 1px solid ${t.border}; border-radius: ${r + 2}px; }
QToolButton[role="section"] { color: ${t.text}; font-weight: 600; border: none; padding: 4px 0; }`,
    plain: `QToolButton[role="section"] { color: ${t.text}; font-weight: 600; border: none; padding: 4px 0; }`,
  };
  return `/* GroomLab: ${o.theme} / ${o.accent}, ${o.density}, radius ${r} — generated by research/ui-redesign */
QWidget { background: ${t.panel}; color: ${t.text}; font-size: ${d.font}px; selection-background-color: ${t.selection}; selection-color: ${t.text}; }
QMainWindow, QMainWindow::separator { background: ${t.background}; }
QMainWindow::separator { width: ${o.chrome === "inset" ? 6 : 1}px; height: ${o.chrome === "inset" ? 6 : 1}px; }
QLabel { background: transparent; }
QLabel[role="dim"] { color: ${t.textDim}; }
QLabel[role="muted"] { color: ${t.textMuted}; font-size: ${d.small}px; }

/* Menus */
QMenuBar { background: ${t.panel}; border-bottom: 1px solid ${t.border}; padding: 2px 4px; }
QMenuBar::item { color: ${t.textDim}; padding: 4px 10px; border-radius: ${r}px; }
QMenuBar::item:selected, QMenuBar::item:pressed { background: ${t.hover}; color: ${t.text}; }
QMenu { background: ${t.raised}; border: 1px solid ${t.border}; border-radius: ${r}px; padding: 4px; }
QMenu::item { padding: 0 24px 0 8px; min-height: ${row}px; border-radius: ${rs}px; }
QMenu::item:selected { background: ${t.selection}; }
QMenu::separator { height: 1px; background: ${t.border}; margin: 4px 4px; }
QToolTip { background: ${t.raised}; color: ${t.text}; border: 1px solid ${t.border}; border-radius: ${r}px; padding: 3px 8px; }

/* Buttons */
QPushButton, QToolButton { background: ${t.raised}; color: ${t.text}; border: 1px solid ${t.border}; border-radius: ${r}px; padding: 0 12px; min-height: ${inner}px; font-weight: 500; }
QPushButton:hover, QToolButton:hover { background: ${t.hover}; }
QPushButton:pressed, QToolButton:pressed, QToolButton:checked { background: ${t.selection}; }
QPushButton:disabled, QToolButton:disabled { color: ${t.textMuted}; }
QPushButton[role="primary"] { background: ${t.accent}; color: ${t.accentText}; border-color: ${t.accent}; font-weight: 600; }
QPushButton[role="ghost"], QToolButton[role="ghost"] { background: transparent; border-color: transparent; color: ${t.textDim}; }
QPushButton[role="ghost"]:hover, QToolButton[role="ghost"]:hover { background: ${t.hover}; color: ${t.text}; }
QToolButton[role="tool"] { background: ${o.tools === "tiles" ? t.raised : "transparent"}; border: 1px solid ${o.tools === "tiles" ? t.border : "transparent"}; color: ${t.textDim}; padding: 4px; }
QToolButton[role="tool"]:checked { background: ${t.selection}; border-color: ${o.tools === "list" ? "transparent" : t.accent}; color: ${t.text}; }

/* Fields */
QLineEdit, QSpinBox, QDoubleSpinBox, QComboBox { background: ${t.raised}; border: 1px solid ${t.border}; border-radius: ${r}px; padding: 0 8px; min-height: ${inner}px; }
QLineEdit:focus, QComboBox:on { border-color: ${t.accent}; }
QComboBox:hover { background: ${t.hover}; }
QComboBox::drop-down { border: none; width: 18px; }
QComboBox QAbstractItemView { background: ${t.raised}; border: 1px solid ${t.border}; border-radius: ${r}px; padding: 4px; outline: none; }
QComboBox QAbstractItemView::item { min-height: ${row}px; border-radius: ${rs}px; padding-left: 8px; }
QComboBox QAbstractItemView::item:selected { background: ${t.selection}; }

/* Sliders (track style; the fill field is a painted widget, see QT.md) */
QSlider::groove:horizontal { height: 4px; border-radius: 2px; background: ${t.track}; }
QSlider::sub-page:horizontal { height: 4px; border-radius: 2px; background: ${t.accent}; }
QSlider::handle:horizontal { width: 12px; height: 12px; margin: -4px 0; border-radius: 6px; background: ${t.text}; border: 1px solid ${t.border}; }

/* On / off */
QCheckBox { spacing: 8px; background: transparent; }
QCheckBox::indicator { width: 14px; height: 14px; border: 1px solid ${t.border}; border-radius: ${Math.min(r, 4)}px; background: ${t.raised}; }
QCheckBox::indicator:checked { background: ${t.accent}; border-color: ${t.accent}; image: url(:/icons/ui_check_${t.dark ? "dark" : "light"}.svg); }

/* Tabs: ${o.tabs} */
${tabs[o.tabs]}

/* Sections: ${o.sections} */
${sections[o.sections]}

/* Docks */
QDockWidget { titlebar-close-icon: none; }
QDockWidget > QWidget${o.chrome === "inset" ? ` { border: 1px solid ${t.border}; border-radius: ${r + 2}px; }` : " { border: none; }"}

/* Scroll bars */
QScrollBar:vertical { background: transparent; width: 8px; margin: 2px; }
QScrollBar::handle:vertical { background: ${t.hover}; border-radius: 3px; min-height: 24px; }
QScrollBar::add-line, QScrollBar::sub-line, QScrollBar::add-page, QScrollBar::sub-page { background: none; height: 0; }
`;
}
