// Copies GroomLab's hair shading and its lines' width as coverage, engine/gpu/shaders/hair_bsdf.glsl
// and line_coverage.glsl (the sources the app and Maya's viewport draw with), into the website's
// viewer as strings: web/components/home/hair-bsdf.ts. Run it when either changes:
//
//   node engine/web/tools/make_hair_bsdf.mjs
//
// (The site builds from web/ alone, so it carries its own copy; a check mode, --check, exits 1 when
// the copy is out of step.)

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const read = (name) => readFileSync(resolve(root, 'engine/gpu/shaders', name), 'utf8').replace(/\r\n/g, '\n');
const glsl = read('hair_bsdf.glsl');
const coverage = read('line_coverage.glsl');
const out = resolve(root, 'web/components/home/hair-bsdf.ts');
const text = `// SPDX-License-Identifier: Apache-2.0
// GENERATED by engine/web/tools/make_hair_bsdf.mjs from engine/gpu/shaders/hair_bsdf.glsl and
// line_coverage.glsl: do not edit. GroomLab's hair shading (Marschner's lobes, dual scattering,
// calibrated against Arnold's aiStandardHair) and its strand lines' width as coverage, the sources
// the app and Maya's viewport draw with too.
export const HAIR_BSDF = ${JSON.stringify(glsl)};
export const LINE_COVERAGE = ${JSON.stringify(coverage)};
`;
if (process.argv.includes('--check')) {
  let now = '';
  try {
    now = readFileSync(out, 'utf8');
  } catch {}
  if (now !== text) {
    console.error(`${out} is out of step with hair_bsdf.glsl: run node engine/web/tools/make_hair_bsdf.mjs`);
    process.exit(1);
  }
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}
